export async function ensureSeed(): Promise<void> {
  const seeded = await one<{ value: string }>("SELECT value FROM settings WHERE key = ?", [
    "seed_version",
  ]);
  if (seeded && seeded.value === "1") return;

  // الإعدادات الافتراضية
  const defaults: Record<string, string> = {
    site_name: "ASBA AI",
    site_tagline: "مدونة الذكاء الاصطناعي والتقنية والإبداع الرقمي",
    site_description:
      "مدونة ASBA AI — مقالات وشروحات ومشاريع في الذكاء الاصطناعي والتقنية والإبداع الرقمي، بلغة عربية واضحة وبأسلوب عملي.",
    author_name: "ASBA AI",
    about_short:
      "ASBA AI مساحة شخصية لنشر المقالات والشروحات والمشاريع في الذكاء الاصطناعي والتقنية، بهدف تقريب هذه التقنيات من القارئ العربي بأسلوب عملي وواضح.",
    contact_email: "",
    footer_text: "© ASBA AI — جميع الحقوق محفوظة",
    theme_accent: "#6366f1",
    logo_media_id: "",
    social_x: "",
    social_facebook: "",
    social_instagram: "",
    social_youtube: "",
    social_telegram: "",
    social_github: "",
    social_linkedin: "",
  };
  for (const [key, value] of Object.entries(defaults)) {
    await setSetting(key, value);
  }

  // التصنيفات
  const catCount = await one<{ c: number }>("SELECT COUNT(*) as c FROM categories");
  if (!catCount || Number(catCount.c) === 0) {
    for (const cat of CATEGORIES) {
      await insert("categories", { ...cat, created_at: nowISO() });
    }
  }

  // الصفحات الثابتة
  const pageCount = await one<{ c: number }>("SELECT COUNT(*) as c FROM pages");
  if (!pageCount || Number(pageCount.c) === 0) {
    for (const p of PAGES) {
      await insert("pages", { ...p, updated_at: nowISO() });
    }
  }

  // مساحات الإعلانات
  const adCount = await one<{ c: number }>("SELECT COUNT(*) as c FROM ads");
  if (!adCount || Number(adCount.c) === 0) {
    for (const placement of ADS) {
      await insert("ads", { placement, code: "", enabled: 0, updated_at: nowISO() });
    }
  }

  // مقال ترحيبي واحد
  const postCount = await one<{ c: number }>("SELECT COUNT(*) as c FROM posts");
  if (!postCount || Number(postCount.c) === 0) {
    const cat = await one<{ id: number }>("SELECT id FROM categories WHERE slug = ?", ["tutorials"]);
    await insert("posts", {
      slug: "welcome-to-asba-ai",
      title: "مرحبًا بك في مدونة ASBA AI",
      excerpt:
        "أول مقال في مدونتك الجديدة: دليل سريع لكل ما تستطيع فعله من لوحة التحكم — النشر، الوسائط، الإعلانات، الإعدادات، والمزيد.",
      content: WELCOME_POST,
      cover_media_id: null,
      cover_url: "/og-default.png",
      category_id: cat ? cat.id : null,
      tags: JSON.stringify(["ترحيب", "ASBA AI"]),
      status: "published",
      published_at: nowISO(),
      featured: 1,
      seo_title: "مرحبًا بك في مدونة ASBA AI — ابدأ من هنا",
      seo_description:
        "دليل سريع للبدء مع منصة ASBA AI: النشر، إدارة الصور، الإعلانات، الإعدادات، والإحصائيات الحقيقية.",
      og_media_id: null,
      views: 0,
      created_at: nowISO(),
      updated_at: nowISO(),
    });
  }

  await setSetting("seed_version", "1");
}
